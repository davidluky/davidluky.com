export const featuredProjects = projects.filter((project) => project.featured);
export type LiveProject = Project & { liveUrl: string };
export const liveProjects = projects.filter((project): project is LiveProject => project.liveUrl?.startsWith("http") === true);
// Public websites exclude restricted surfaces, demos and store listings.
export const publicWebProjects = projects.filter((project): project is LiveProject =>
  Boolean(project.liveUrl) && project.availability === "public" && project.tag !== "mobile-app"
);

export function getProjectTag(project: Project) {
  return projectTags[project.tag];
}

export function getProjectStatus(project: Project) {
  return projectStatuses[project.status];
}

export function getProjectVisibility(project: Project) {
  return projectVisibilities[project.visibility];
}

/** Product access is separate from source visibility and release maturity. */
export function getProjectAvailability(project: Project) {
  const availability = project.availability ?? (
    project.visibility === "internal" || project.status === "internal"
      ? "internal"
      : project.liveUrl || (project.visibility === "public" && project.repoUrl)
        ? "public"
        : "unavailable"
  );
  return projectAvailabilities[availability];
}
